// Get current language from localStorage or default to French
let currentLang = localStorage.getItem('preferredLanguage') || 'fr';

// Function to translate project cards
function translateProjectCards(lang) {
    const projectCards = document.querySelectorAll('.project-card');

    projectCards.forEach(card => {
        const onclick = card.getAttribute('onclick');
        if (!onclick) return;

        // Extract project ID from onclick attribute (e.g., "openModal('infographie')")
        const match = onclick.match(/openModal\('([^']+)'\)/);
        if (!match) return;

        const projectId = match[1];
        const projectTranslation = translations[lang]?.projects?.[projectId];

        if (projectTranslation) {
            const titleElement = card.querySelector('.card-info h3');
            const subtitleElement = card.querySelector('.card-info p');
            const tagsElement = card.querySelector('.card-tags');
            const viewBtn = card.querySelector('.view-btn');

            if (titleElement) titleElement.textContent = projectTranslation.title;
            if (subtitleElement) subtitleElement.textContent = projectTranslation.subtitle;
            if (tagsElement) tagsElement.innerHTML = projectTranslation.tags;
            if (viewBtn) viewBtn.textContent = translations[lang]?.common?.viewProject || 'View project';
        }
    });
}

// Function to translate modal headers
function translateModalHeaders(lang) {
    const modalTitles = {
        'modal-title': 'Titre du projet',  // This will be updated dynamically when opening
    };

    // Update static modal texts
    const contextTitle = document.querySelector('.modal-body h3:nth-of-type(1)');
    const missionsTitle = document.querySelector('.modal-body h3:nth-of-type(2)');
    const skillsTitle = document.querySelector('.modal-body h3:nth-of-type(3)');
    const techTitle = document.querySelector('.modal-body h3:nth-of-type(4)');

    if (contextTitle) contextTitle.textContent = translations[lang]?.common?.contextObjectives || 'Context and objectives';
    if (missionsTitle) missionsTitle.textContent = translations[lang]?.common?.missions || 'Missions completed';
    if (skillsTitle) skillsTitle.textContent = translations[lang]?.common?.skills || 'Skills';
    if (techTitle) techTitle.textContent = translations[lang]?.common?.technologies || 'Technologies';
}

// Function to translate the page
function translatePage(lang) {
    currentLang = lang;
    localStorage.setItem('preferredLanguage', lang);

    // Update HTML lang attribute
    document.documentElement.lang = lang;

    // Find all elements with data-i18n attribute
    const elements = document.querySelectorAll('[data-i18n]');

    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        const keys = key.split('.');
        let translation = translations[lang];

        // Navigate through nested keys
        for (const k of keys) {
            if (translation && translation[k]) {
                translation = translation[k];
            } else {
                console.warn(`Translation not found for key: ${key}`);
                return;
            }
        }

        // Update element content
        element.textContent = translation;
    });

    // Find all elements with data-i18n-placeholder attribute
    const placeholderElements = document.querySelectorAll('[data-i18n-placeholder]');

    placeholderElements.forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        const keys = key.split('.');
        let translation = translations[lang];

        // Navigate through nested keys
        for (const k of keys) {
            if (translation && translation[k]) {
                translation = translation[k];
            } else {
                console.warn(`Translation not found for placeholder key: ${key}`);
                return;
            }
        }

        // Update placeholder
        element.placeholder = translation;
    });

    // Translate project cards
    translateProjectCards(lang);

    // Translate modal headers
    translateModalHeaders(lang);

    // Update active language button
    updateLanguageButtons(lang);
}

// Function to update language button states
function updateLanguageButtons(lang) {
    const buttons = document.querySelectorAll('.lang-option');
    buttons.forEach(btn => {
        if (btn.dataset.lang === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });
}

// Initialize on page load
document.addEventListener('DOMContentLoaded', () => {
    // Apply saved language preference
    translatePage(currentLang);

    // Add event listeners to language buttons
    const langButtons = document.querySelectorAll('.lang-option');
    langButtons.forEach(btn => {
        btn.addEventListener('click', () => {
            const lang = btn.dataset.lang;
            translatePage(lang);
        });
    });
});
